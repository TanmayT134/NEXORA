package com.nexora.nexora_backend.entity;

import java.time.LocalDateTime;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Entity
@Table(
    name = "interview_questions",
    uniqueConstraints = {
        @UniqueConstraint(
            name = "uk_session_question_sequence",
            columnNames = {"session_id", "sequence_number"}
        )
    }
)
@Getter
@Setter
@NoArgsConstructor
public class InterviewQuestion {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Interview session to which this question belongs
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "session_id", nullable = false)
    private InterviewSession session;

    // Position of the question in the interview
    @Column(name = "sequence_number", nullable = false)
    private Integer sequenceNumber;

    // Actual question generated by AI
    @Column(name = "question_text", nullable = false, columnDefinition = "LONGTEXT")
    private String questionText;

    // Category of question
    @Enumerated(EnumType.STRING)
    @Column(name = "question_type", nullable = false, length = 30)
    private InterviewQuestionType questionType;

    // Skill associated with this question
    @Column(name = "skill_name", length = 100)
    private String skillName;

    // The immediately preceding question when this is an adaptive follow-up.
    // A null parent marks a main topic question.
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "parent_question_id")
    private InterviewQuestion parentQuestion;

    // 0 for main questions; 1..N for follow-up depth.
    @Column(name = "follow_up_depth", nullable = false, columnDefinition = "INT NOT NULL DEFAULT 0")
    private Integer followUpDepth = 0;

    // Internal evaluation guidance for later AI evaluation
    @Column(name = "evaluation_criteria", columnDefinition = "LONGTEXT")
    private String evaluationCriteria;

    @Column(name = "generated_at", nullable = false, updatable = false)
    private LocalDateTime generatedAt;

    @PrePersist
    protected void onCreate() {
        generatedAt = LocalDateTime.now();
    }
}